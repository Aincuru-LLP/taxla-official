def build_dataset() -> List[Dict[str, str]]:
    """Convert the (division, group, code, description) tuples into the JSON shape."""
    seen_5digit = set()
    output: List[Dict[str, str]] = []
    for div2, grp4, code5, desc in SUBCLASSES:
        if code5 in seen_5digit:
            raise ValueError(f"Duplicate 5-digit subclass {code5} ({desc!r})")
        seen_5digit.add(code5)
        if not (len(div2) == 2 and len(grp4) == 4 and len(code5) == 5):
            raise ValueError(f"Bad code width: div={div2!r} grp={grp4!r} code={code5!r}")
        if not code5.startswith(grp4):
            raise ValueError(
                f"Subclass {code5} ({desc!r}) does not start with group {grp4}"
            )
        if not grp4.startswith(div2):
            raise ValueError(
                f"Group {grp4} ({desc!r}) does not start with division {div2}"
            )
        output.append({
            "nic_2digit": div2,
            "nic_4digit": grp4,
            "nic_5digit": code5,
            "description": desc,
        })
    return output


