"""Phase 07 — Placeholder certificate PDF generator.

We deliberately avoid pulling in a PDF library for the placeholder:

  * The "real" certificate is captured by the Playwright worker from the
    Udyam portal (Phase 09). Anything we generate here gets overwritten
    with that capture as soon as the workflow reaches ``COMPLETED``.
  * The placeholder just has to (a) be a valid PDF, (b) identify the
    application + business so support staff can find the right one on
    disk, and (c) render in any browser.
  * No deps = no cross-platform install pain (WeasyPrint needs GTK on
    Windows; reportlab + fpdf2 work everywhere but add ~20 MB).

The implementation writes a one-page PDF by hand (PDF 1.4 + standard 14
fonts). It is intentionally tiny and easy to read; if a future requirement
needs headings / tables / branding, swap this module for one that uses a
real library.

Public surface:
    generate_certificate_pdf(application, business_name, output_path) -> None
"""
from __future__ import annotations

import io
import os
import zlib
from datetime import datetime, timezone
from typing import Optional


def _pdf_ascii(text: str) -> str:
    """Normalise a Python string to PDF-safe ASCII.

    Helvetica is a PDF base-14 font that only encodes latin-1; we
    intentionally keep the placeholder strictly ASCII by replacing
    any character outside that range with a sensible substitute. The
    placeholder is overwritten by the real Udyam certificate in
    Phase 09, so multi-byte Unicode is not a use-case.
    """
    # Common typographic punctuation that survives visually.
    replacements = {
        "—": "--",   # em dash
        "–": "-",    # en dash
        "‘": "'",    # left single quote
        "’": "'",    # right single quote
        "“": '"',    # left double quote
        "”": '"',    # right double quote
        "…": "...",  # ellipsis
        " ": " ",    # non-breaking space
    }
    for src, dst in replacements.items():
        text = text.replace(src, dst)
    # Final belt-and-braces: replace any remaining non-ASCII with '?'.
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _pdf_escape(text: str) -> str:
    """Escape a Python string for use inside a PDF text object."""
    return (
        text.replace("\\", "\\\\")
            .replace("(", "\\(")
            .replace(")", "\\)")
    )


def _pdf_stream(content: bytes) -> bytes:
    """Wrap raw bytes as a Flate-compressed PDF stream object."""
    compressed = zlib.compress(content)
    return (
        b"<< /Filter /FlateDecode /Length "
        + str(len(compressed)).encode("ascii")
        + b" >>\nstream\n"
        + compressed
        + b"\nendstream"
    )


def _build_pdf_bytes(
    *,
    application_number: str,
    business_name: str,
    applicant_name: str,
    pan_number: str,
    issued_at: datetime,
    registration_number: str,
) -> bytes:
    """Render the placeholder PDF bytes. Layout:

        [Title: UDYAM REGISTRATION CERTIFICATE — placeholder]
        line 1: Application Number: <app>
        line 2: Business Name:       <business>
        line 3: Applicant Name:      <name>
        line 4: PAN:                 <pan>
        line 5: Udyam Reg. Number:   <reg>
        line 6: Issued At:           <iso timestamp>
        line 7: Note: This document is a placeholder. The official
                  certificate is captured from the Udyam portal by
                  the Playwright worker.
    """
    title = "UDYAM REGISTRATION CERTIFICATE — placeholder"
    notice = (
        "NOTE: This document is a placeholder generated by the TAXLA "
        "platform. The official certificate is captured from the Udyam "
        "portal by the Playwright worker (Phase 09) and replaces this "
        "file once the application reaches COMPLETED."
    )

    # PDF text operators: position with Td, draw string with Tj.
    # Each Td uses 1/72 inch; default font is Helvetica 12pt.
    lines: list[tuple[str, float, float]] = [
        (title, 50, 760),
        (f"Application Number: {application_number}", 50, 720),
        (f"Business Name:       {business_name}", 50, 695),
        (f"Applicant Name:      {applicant_name}", 50, 670),
        (f"PAN:                 {pan_number}", 50, 645),
        (f"Udyam Reg. Number:   {registration_number}", 50, 620),
        (f"Issued At:           {issued_at.isoformat()}", 50, 595),
    ]
    # Split the notice across a few lines so the column is wide enough.
    notice_x = 50
    notice_y = 540
    notice_chunks = [notice[i:i + 78] for i in range(0, len(notice), 78)]
    for chunk in notice_chunks:
        lines.append((chunk, notice_x, notice_y))
        notice_y -= 18

    content_parts: list[bytes] = [b"BT\n/F1 12 Tf\n"]
    for text, x, y in lines:
        safe = _pdf_escape(_pdf_ascii(text))
        content_parts.append(
            f"1 0 0 1 {x} {y} Tm\n({safe}) Tj\n".encode("latin-1")
        )
    content_parts.append(b"ET\n")
    content = b"".join(content_parts)

    stream = _pdf_stream(content)

    # Build the PDF object table.
    objects: list[bytes] = []
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")          # 1
    objects.append(b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>")   # 2
    objects.append(
        b"<< /Type /Page /Parent 2 0 R "
        b"/MediaBox [0 0 595 842] "  # A4 in points
        b"/Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R >> >> >>"
    )                                                            # 3
    objects.append(stream)                                        # 4
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")  # 5

    out = io.BytesIO()
    out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")  # binary marker
    offsets: list[int] = []
    for index, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{index} 0 obj\n".encode("ascii"))
        out.write(body)
        out.write(b"\nendobj\n")
    xref_offset = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    out.write(b"0000000000 65535 f \n")
    for offset in offsets:
        out.write(f"{offset:010d} 00000 n \n".encode("ascii"))
    out.write(b"trailer\n")
    out.write(f"<< /Size {len(objects) + 1} /Root 1 0 R >>\n".encode("ascii"))
    out.write(b"startxref\n")
    out.write(f"{xref_offset}\n".encode("ascii"))
    out.write(b"%%EOF\n")
    return out.getvalue()


def generate_certificate_pdf(
    *,
    application_id: str,
    application_number: str,
    business_name: str,
    applicant_name: str,
    pan_number: str,
    registration_number: str,
    output_path: str,
    issued_at: Optional[datetime] = None,
) -> str:
    """Write a placeholder PDF to ``output_path``.

    Returns the absolute path of the written file. Raises OSError on I/O
    failure (the caller should treat this as a non-fatal workflow event
    rather than a request-breaking exception — the application can still
    progress; the certificate will simply be regenerated on the next
    attempt).
    """
    ts = issued_at or datetime.now(timezone.utc)
    pdf_bytes = _build_pdf_bytes(
        application_number=application_number,
        business_name=business_name,
        applicant_name=applicant_name,
        pan_number=pan_number,
        issued_at=ts,
        registration_number=registration_number,
    )
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "wb") as f:
        f.write(pdf_bytes)
    return os.path.abspath(output_path)


def render_certificate_pdf(
    *,
    application_number: str,
    business_name: str,
    applicant_name: str,
    pan_number: str,
    registration_number: str,
    issued_at: Optional[datetime] = None,
) -> bytes:
    """Same content as :func:`generate_certificate_pdf`, returned as bytes.

    Useful for tests that want to verify the bytes without touching disk.
    """
    ts = issued_at or datetime.now(timezone.utc)
    return _build_pdf_bytes(
        application_number=application_number,
        business_name=business_name,
        applicant_name=applicant_name,
        pan_number=pan_number,
        issued_at=ts,
        registration_number=registration_number,
    )